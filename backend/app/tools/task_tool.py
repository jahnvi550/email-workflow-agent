"""
Task Tool for managing Kanban tasks generated by the Agent.
"""

from datetime import datetime
from typing import Dict, Any, List, Optional
from sqlalchemy.orm import Session
from backend.app.models.task import ExtractedTask
from backend.app.models.audit_log import AuditLog


class TaskTool:
    @staticmethod
    def create_task_from_dict(db: Session, email_id: Optional[str], task_data: Dict[str, Any]) -> ExtractedTask:
        """Persists an extracted task to the database."""
        deadline = None
        if task_data.get("deadline"):
            try:
                deadline_str = task_data["deadline"].replace("Z", "")
                if "T" in deadline_str:
                    deadline = datetime.fromisoformat(deadline_str)
                else:
                    deadline = datetime.strptime(deadline_str, "%Y-%m-%d")
            except Exception:
                deadline = None

        new_task = ExtractedTask(
            email_id=email_id,
            title=task_data.get("title", "Untitled Task"),
            description=task_data.get("description", ""),
            deadline=deadline,
            priority=task_data.get("priority", "MEDIUM"),
            priority_reason=task_data.get("priority_reason") or task_data.get("reason"),
            status=task_data.get("status", "TODO"),
            assignee=task_data.get("assignee", "AI Agent"),
            estimated_hours=task_data.get("estimated_hours") or task_data.get("effort"),
            subtasks=task_data.get("subtasks", []),
            tags=task_data.get("tags", [])
        )
        db.add(new_task)
        db.commit()
        db.refresh(new_task)


        # Audit Log
        audit = AuditLog(
            action="TASK_CREATED",
            actor="AI_AGENT",
            entity_type="TASK",
            entity_id=new_task.id,
            details={"title": new_task.title, "priority": new_task.priority, "deadline": str(new_task.deadline)}
        )
        db.add(audit)
        db.commit()

        return new_task

    @staticmethod
    def update_task_status(db: Session, task_id: str, new_status: str) -> Optional[ExtractedTask]:
        task = db.query(ExtractedTask).filter(ExtractedTask.id == task_id).first()
        if not task:
            return None
        old_status = task.status
        task.status = new_status
        task.updated_at = datetime.utcnow()
        db.commit()
        db.refresh(task)

        audit = AuditLog(
            action="TASK_STATUS_UPDATED",
            actor="HUMAN_USER",
            entity_type="TASK",
            entity_id=task.id,
            details={"old_status": old_status, "new_status": new_status, "title": task.title}
        )
        db.add(audit)
        db.commit()
        return task
